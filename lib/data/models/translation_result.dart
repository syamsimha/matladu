/// Status of an on-device translation operation.
enum TranslationStatus {
  /// Engine is idle, waiting for input.
  idle,

  /// On-device neural inference is actively running.
  translating,

  /// Translation completed successfully with genuine on-device inference.
  completed,

  /// Required on-device translation model pack is not installed locally.
  modelMissing,

  /// The requested language pair is not supported by the local model.
  unsupportedPair,

  /// An error occurred during model loading or neural inference.
  error,
}

/// Represents the result of an on-device translation operation.
///
/// STRICT PRIVACY GUARANTEES:
/// - 100% On-Device: Text is translated locally within the application sandbox.
/// - Zero Cloud Egress: No transcripts or translations are ever transmitted over the network.
/// - Authenticity: [isMock] is strictly `false` when generated by genuine on-device inference.
class TranslationResult {
  final String originalText;
  final String translatedText;
  final String sourceLanguageCode;
  final String targetLanguageCode;
  final String? sourceLanguageName;
  final String? targetLanguageName;
  final TranslationStatus status;
  final String? errorMessage;
  final String? noticeMessage;
  final Duration duration;
  final bool isMock;
  final DateTime timestamp;

  const TranslationResult({
    required this.originalText,
    required this.translatedText,
    required this.sourceLanguageCode,
    required this.targetLanguageCode,
    this.sourceLanguageName,
    this.targetLanguageName,
    required this.status,
    this.errorMessage,
    this.noticeMessage,
    this.duration = Duration.zero,
    this.isMock = false,
    required this.timestamp,
  });

  bool get isSuccess => status == TranslationStatus.completed;
  bool get hasText => translatedText.trim().isNotEmpty;
  bool get hasError => status == TranslationStatus.error || errorMessage != null;
  bool get isModelMissing => status == TranslationStatus.modelMissing;
  bool get isQuotaExhaustedFallback => noticeMessage != null;
  bool get isSameLanguage =>
      sourceLanguageCode.toLowerCase() == targetLanguageCode.toLowerCase();

  /// Empty result when input speech or text is empty.
  factory TranslationResult.empty({
    String sourceLang = 'en',
    String targetLang = 'te',
  }) {
    return TranslationResult(
      originalText: '',
      translatedText: '',
      sourceLanguageCode: sourceLang,
      targetLanguageCode: targetLang,
      status: TranslationStatus.completed,
      duration: Duration.zero,
      isMock: false,
      timestamp: DateTime.now(),
    );
  }

  /// Result when source and target languages are identical (no inference overhead needed).
  factory TranslationResult.sameLanguage({
    required String text,
    required String languageCode,
    String? languageName,
  }) {
    return TranslationResult(
      originalText: text,
      translatedText: text,
      sourceLanguageCode: languageCode,
      targetLanguageCode: languageCode,
      sourceLanguageName: languageName,
      targetLanguageName: languageName,
      status: TranslationStatus.completed,
      duration: Duration.zero,
      isMock: false,
      timestamp: DateTime.now(),
    );
  }

  /// Result when a required on-device model pack is not installed locally.
  factory TranslationResult.modelMissing({
    required String text,
    required String sourceLang,
    required String targetLang,
    required String missingLanguageName,
  }) {
    return TranslationResult(
      originalText: text,
      translatedText: '',
      sourceLanguageCode: sourceLang,
      targetLanguageCode: targetLang,
      status: TranslationStatus.modelMissing,
      errorMessage:
          'Offline pack required: The on-device translation model for $missingLanguageName is not downloaded. Please download it in Offline Packs.',
      duration: Duration.zero,
      isMock: false,
      timestamp: DateTime.now(),
    );
  }

  /// Result when language pair is not supported by local model.
  factory TranslationResult.unsupportedPair({
    required String text,
    required String sourceLang,
    required String targetLang,
  }) {
    return TranslationResult(
      originalText: text,
      translatedText: '',
      sourceLanguageCode: sourceLang,
      targetLanguageCode: targetLang,
      status: TranslationStatus.unsupportedPair,
      errorMessage:
          'Unsupported language pair: Translation between $sourceLang and $targetLang is not supported by the on-device engine.',
      duration: Duration.zero,
      isMock: false,
      timestamp: DateTime.now(),
    );
  }

  /// Result when inference fails with an exception.
  factory TranslationResult.error({
    required String text,
    required String sourceLang,
    required String targetLang,
    required String errorMessage,
    Duration duration = Duration.zero,
  }) {
    return TranslationResult(
      originalText: text,
      translatedText: '',
      sourceLanguageCode: sourceLang,
      targetLanguageCode: targetLang,
      status: TranslationStatus.error,
      errorMessage: errorMessage,
      duration: duration,
      isMock: false,
      timestamp: DateTime.now(),
    );
  }

  /// Successful genuine translation result.
  factory TranslationResult.success({
    required String originalText,
    required String translatedText,
    required String sourceLanguageCode,
    required String targetLanguageCode,
    String? sourceLanguageName,
    String? targetLanguageName,
    String? noticeMessage,
    Duration duration = Duration.zero,
    bool isMock = false,
  }) {
    return TranslationResult(
      originalText: originalText,
      translatedText: translatedText,
      sourceLanguageCode: sourceLanguageCode,
      targetLanguageCode: targetLanguageCode,
      sourceLanguageName: sourceLanguageName,
      targetLanguageName: targetLanguageName,
      status: TranslationStatus.completed,
      noticeMessage: noticeMessage,
      duration: duration,
      isMock: isMock,
      timestamp: DateTime.now(),
    );
  }

  TranslationResult copyWith({
    String? originalText,
    String? translatedText,
    String? sourceLanguageCode,
    String? targetLanguageCode,
    String? sourceLanguageName,
    String? targetLanguageName,
    TranslationStatus? status,
    String? errorMessage,
    String? noticeMessage,
    Duration? duration,
    bool? isMock,
    DateTime? timestamp,
  }) {
    return TranslationResult(
      originalText: originalText ?? this.originalText,
      translatedText: translatedText ?? this.translatedText,
      sourceLanguageCode: sourceLanguageCode ?? this.sourceLanguageCode,
      targetLanguageCode: targetLanguageCode ?? this.targetLanguageCode,
      sourceLanguageName: sourceLanguageName ?? this.sourceLanguageName,
      targetLanguageName: targetLanguageName ?? this.targetLanguageName,
      status: status ?? this.status,
      errorMessage: errorMessage ?? this.errorMessage,
      noticeMessage: noticeMessage ?? this.noticeMessage,
      duration: duration ?? this.duration,
      isMock: isMock ?? this.isMock,
      timestamp: timestamp ?? this.timestamp,
    );
  }

  Map<String, dynamic> toJson() => {
        'originalText': originalText,
        'translatedText': translatedText,
        'sourceLanguageCode': sourceLanguageCode,
        'targetLanguageCode': targetLanguageCode,
        'sourceLanguageName': sourceLanguageName,
        'targetLanguageName': targetLanguageName,
        'status': status.name,
        'errorMessage': errorMessage,
        'noticeMessage': noticeMessage,
        'durationMs': duration.inMilliseconds,
        'isMock': isMock,
        'timestamp': timestamp.toIso8601String(),
      };

  @override
  String toString() =>
      'TranslationResult(original: "$originalText", translated: "$translatedText", $sourceLanguageCode -> $targetLanguageCode, status: $status, duration: ${duration.inMilliseconds}ms, isMock: $isMock)';
}

